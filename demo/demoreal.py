def sentiment_score(tokens):
    if not isinstance(tokens, list):
        return 0
    score = 0
    for word in tokens:
        if word in positive_dict:
            score += positive_dict[word]
        elif word in negative_dict:
            score += negative_dict[word]
    return score

def get_sentiment_label(score):
    if score > 0:
        return "positif"
    elif score < 0:
        return "negatif"
    else:
        return "netral"

def predict_sentiment(text):

    # Preprocessing
    clean = clean_text(text)
    folded = case_folding(clean)
    normalized = normalize_slang(folded)
    no_stopword = remove_stopwords(normalized)
    stemmed = stemming(no_stopword)
    tokens = tokenize(stemmed)

    # InSet Lexicon
    score = sentiment_score(tokens)

    # Label sentimen
    sentiment = get_sentiment_label(score)

    return {
        "input": text,
        "clean_text": clean,
        "case_folding": folded,
        "slang_normalization": normalized,
        "stopword_removed": no_stopword,
        "stemmed": stemmed,
        "tokens": tokens,
        "score": score,
        "sentiment": sentiment
    }

def predict_cnn(text):

    # Preprocessing
    clean_text = preprocess_text(text)

    # Tokenization menggunakan tokenizer CNN
    sequence = tokenizer.texts_to_sequences([clean_text])

    # Padding sesuai input model
    padded = pad_sequences(
        sequence,
        maxlen=100,
        padding="post",
        truncating="post"
    )

    # Prediksi
    prediction = model.predict(
        padded,
        verbose=0
    )

    # Ambil kelas dengan probabilitas terbesar
    pred_class = np.argmax(prediction, axis=1)[0]

    # Ubah angka menjadi nama kelas
    label = le.inverse_transform([pred_class])[0]

    # Confidence
    confidence = float(prediction[0][pred_class])

    return label, confidence, prediction


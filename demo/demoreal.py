def predict_text(text):
    # 1. PREPROCESSING + SENTIMENT
    sentiment_result = predict_sentiment(text)
    processed_text = sentiment_result["stemmed"]
    tokens = sentiment_result["tokens"]
    sentiment_score = sentiment_result["score"]
    sentiment = sentiment_result["sentiment"]

    # 2. JIKA POSITIF / NETRAL → BERHENTI
    if sentiment != "negatif":
        return {
            "input": text,
            "processed": processed_text,
            "tokens": tokens,
            "sentiment_score": sentiment_score,
            "sentiment": sentiment,
            "cyberbullying": None,
            "confidence": None,
            "law": None
        }

    # 3. JIKA NEGATIF → CNN
    sequence = tokenizer.texts_to_sequences(
        [processed_text]
    )
    padded = pad_sequences(
        sequence,
        maxlen=100,
        padding="post",
        truncating="post"
    )
    prediction = model.predict(
        padded,
        verbose=0
    )
    pred_class = np.argmax(
        prediction,
        axis=1
    )[0]
    label = le.inverse_transform(
        [pred_class]
    )[0]

    confidence = float(
        prediction[0][pred_class]
    )

    # 4. PEMETAAN REGULASI
    law = map_to_law(label)

    # 5. HASIL
    return {
        "input": text,
        "processed": processed_text,
        "tokens": tokens,
        "sentiment_score": sentiment_score,
        "sentiment": sentiment,
        "cyberbullying": label,
        "confidence": confidence,
        "law": law
    }

